function q(
  id: string,
  prompt_ar: string,
  choices_ar: string[],
  correct_index: number,
  traps: [string, string, string],
  solve_ar: string,
  difficulty: "easy" | "mid" | "hard",
) {
  const trap_explanations_ar: Record<number, string> = {};
  let ti = 0;
  for (let i = 0; i < 4; i++) {
    if (i === correct_index) continue;
    trap_explanations_ar[i] = traps[ti++]!;
  }
  return {
    id,
    prompt_ar,
    choices_ar,
    correct_index,
    trap_explanations_ar,
    solve_ar,
    trick_ref: "check-by-sub",
    difficulty,
    sub_pattern: "algebra" as const,
    ...review,
  };
}

